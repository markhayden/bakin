/**
 * Deterministic source-tree hashing for the plugin lockfile.
 *
 * `sourceTreeSha` values recorded in `~/.bakin/plugins/lock.json` let the
 * install/upgrade flows detect whether a local plugin source changed since
 * it was last installed/rebuilt, without trusting mtimes — and, since
 * #1007, name the IDENTITY a local upgrade is held to: the digest must
 * cover exactly the bytes a local install or upgrade transfers.
 *
 * LOCKFILE HASHER (algo 3): every regular file under the root except the
 * root-level entries a transfer never carries (`LOCAL_SOURCE_ROOT_SKIP`:
 * `dist` and `node_modules` are regenerated by the build, `.git` is not
 * runtime, the install sentinel is the transaction's own). Dot entries and
 * nested `dist`/`node_modules` ARE covered — install keeps them
 * (`.runtime.json`, `assets/dist/schema.json` are ordinary runtime inputs),
 * so the upgrade transfers them too and the digest vouches for them.
 * Symlinks are not hashed; the upgrade refuses a snapshot that carries one.
 *
 * The Whiskit `hashSourceTree` (algo 2; sorted rel+filehash lines, skipping
 * NON_RUNTIME_DIRS + dotfiles) answers a DIFFERENT question — what runtime
 * source went into a published artifact — and lives on in checksummed
 * `.whiskit/build.json` provenance, so it stays as it is; stored algo-2
 * rows migrate once, like the algo-1 rows before them. The repo once had
 * two hashers by accident (audit finding); these two are deliberate, each
 * named by what it covers.
 */
import { cpSync, existsSync, readFileSync, readdirSync, statSync } from 'fs'
import { join, relative, sep } from 'path'
import { createHash } from 'crypto'
import type { PluginLockEntry } from '@bakin/core/plugins/lockfile'
import { hasDeclaredDeps } from '@/core/whiskit/build'
import { hashSourceTree } from '@/core/whiskit/source-hash'

/**
 * `PluginLockEntry.sourceTreeShaAlgo` value written for hashes produced by
 * the lockfile hasher. Rows without the field hold legacy (algo 1) hashes,
 * rows with `2` hold Whiskit-formula hashes; both migrate on the first
 * check/upgrade that observes the source unchanged.
 */
export const SOURCE_TREE_SHA_ALGO = 3

/** Root-level entries a local-source transfer never carries: regenerated by the build (`dist`), not runtime (`.git`), or the transaction's own. */
export const LOCAL_SOURCE_ROOT_SKIP: ReadonlySet<string> = new Set(['dist', '.git', '.bakin-install.json'])

/** What a local source transfers (and so what its digest covers). */
export interface LocalTransferPolicy {
  /** True when the build's dependency install regenerates root `node_modules` — it is skipped; otherwise it is VENDORED: transferred and hashed (review r9 #3). */
  regeneratesModules: boolean
  transfers(rel: string): boolean
}

/**
 * The policy for one source root, decided by the SAME predicate the builder
 * uses to run `bun install` (`hasDeclaredDeps`): a plugin that declares
 * dependencies gets its `node_modules` regenerated, one that declares none
 * may legitimately import vendored modules relatively and keeps them.
 */
export function localTransferPolicy(rootDir: string): LocalTransferPolicy {
  let regeneratesModules = false
  const pkgPath = join(rootDir, 'package.json')
  if (existsSync(pkgPath)) {
    try {
      regeneratesModules = hasDeclaredDeps(JSON.parse(readFileSync(pkgPath, 'utf-8')) as Parameters<typeof hasDeclaredDeps>[0])
    } catch {
      regeneratesModules = false // an unreadable package.json declares nothing; the build reports it
    }
  }
  return {
    regeneratesModules,
    transfers(rel) {
      const first = rel.split('/')[0] ?? ''
      if (LOCAL_SOURCE_ROOT_SKIP.has(first)) return false
      return !(regeneratesModules && first === 'node_modules')
    },
  }
}

/**
 * ONE transfer policy for a local plugin source — the install's staging copy
 * and the upgrade's snapshot copy the same set, which is exactly what the
 * lockfile digest covers. Symlinks are copied as links (the upgrade refuses
 * them afterwards; the install records what it was given).
 */
export function copyLocalSource(from: string, to: string): void {
  const policy = localTransferPolicy(from)
  cpSync(from, to, {
    recursive: true,
    dereference: false,
    filter: (src) => src === from || policy.transfers(relative(from, src).split(sep).join('/')),
  })
}

function hashFile(path: string): string {
  return createHash('sha256').update(readFileSync(path)).digest('hex')
}

/**
 * Hash a directory's transferable source tree (algo 3). Path-and-content
 * only — mtimes intentionally excluded so the hash is stable across copies
 * of the same source (deliberate design decision; see
 * .claude/knowledge/plugin-lifecycle.md).
 */
export function computeSourceTreeSha(rootDir: string, options: { omitRootEntries?: ReadonlySet<string> } = {}): string {
  const policy = localTransferPolicy(rootDir)
  const omit = options.omitRootEntries ?? new Set<string>()
  const lines: string[] = []
  const walk = (current: string): void => {
    for (const entry of readdirSync(current, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const full = join(current, entry.name)
      const rel = relative(rootDir, full).split(sep).join('/')
      if (!policy.transfers(rel) || (current === rootDir && omit.has(entry.name))) continue
      if (entry.isDirectory()) walk(full)
      else if (entry.isFile()) lines.push(`${rel}\n${hashFile(full)}`)
    }
  }
  walk(rootDir)
  return createHash('sha256').update(lines.join('\n')).digest('hex')
}

/**
 * Every symlink a tree carries, as `/`-joined paths relative to `rootDir`.
 * The hasher IGNORES symlinks, so a digest can never vouch for what a link
 * points at; a local upgrade refuses a snapshot that carries one instead
 * of installing bytes nobody reviewed (#1007 review r6 #1).
 */
export function symlinksIn(rootDir: string): string[] {
  const found: string[] = []
  const walk = (current: string): void => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const full = join(current, entry.name)
      if (entry.isSymbolicLink()) found.push(relative(rootDir, full).split(sep).join('/'))
      else if (entry.isDirectory()) walk(full)
    }
  }
  walk(rootDir)
  return found.sort()
}

/**
 * The pre-consolidation lockfile hasher (algo 1): concatenated rel+bytes,
 * skipping only node_modules/dist/.git. Retained SOLELY so stored legacy
 * shas can be verified once during migration — never write new values
 * with it.
 */
export function legacySourceTreeSha(rootDir: string): string {
  const SKIP = new Set(['node_modules', 'dist', '.git'])
  const files: Array<{ rel: string; data: Buffer }> = []
  function walk(dir: string): void {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (SKIP.has(entry.name)) continue
      const full = join(dir, entry.name)
      if (entry.isDirectory()) {
        walk(full)
      } else if (entry.isFile()) {
        const data = readFileSync(full)
        files.push({ rel: relative(rootDir, full), data })
      }
    }
  }
  if (statSync(rootDir).isDirectory()) walk(rootDir)
  files.sort((a, b) => (a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0))
  const hash = createHash('sha256')
  for (const f of files) {
    hash.update(f.rel)
    hash.update('\0')
    hash.update(f.data)
    hash.update('\0')
  }
  return hash.digest('hex')
}

export interface SourceTreeComparison {
  /** Lockfile (algo 3) hash of the live source tree. */
  liveSha: string
  /** True when the live source differs from what the lockfile recorded. */
  changed: boolean
  /**
   * True when the stored sha was produced by the legacy algorithm and the
   * source is UNCHANGED — the caller should rewrite the row once with
   * `liveSha` + `sourceTreeShaAlgo: SOURCE_TREE_SHA_ALGO` so future
   * comparisons take the canonical fast path. Never true for changed
   * sources: a genuine change must keep reporting as changed, and the
   * eventual upgrade commit writes the canonical sha anyway.
   */
  needsAlgoMigration: boolean
}

/**
 * Compare a lockfile entry's stored source-tree sha against the live
 * source directory, transparently handling legacy rows: a stored legacy sha
 * is verified with its own hasher so a hasher change never spuriously
 * reports "source changed" for an untouched install — and, because an older
 * formula covered LESS than the lockfile hasher, an "unchanged" verdict
 * under it is never the end: the algo-3 baseline is taken from the
 * INSTALLED tree (`installedDir`, what was actually transferred), so a change
 * confined to a newly covered path (a dotfile, a nested dist) is reported
 * instead of silently stamped as the baseline (#1007 review r9 #2).
 */
export function compareStoredSourceTreeSha(
  entry: Pick<PluginLockEntry, 'sourceTreeSha' | 'sourceTreeShaAlgo'>,
  sourcePath: string,
  installedDir: string,
): SourceTreeComparison {
  const liveSha = computeSourceTreeSha(sourcePath)
  if (!entry.sourceTreeSha) {
    return { liveSha, changed: true, needsAlgoMigration: false }
  }
  if (entry.sourceTreeShaAlgo === SOURCE_TREE_SHA_ALGO) {
    return { liveSha, changed: liveSha !== entry.sourceTreeSha, needsAlgoMigration: false }
  }
  // Legacy row: is the source unchanged under the formula that WROTE the
  // row? Algo 2 rows hold the Whiskit formula; rows without the field hold
  // the pre-consolidation formula — or the lockfile formula itself, for
  // fixtures written before the field existed. (The two current formulas
  // coincide on a tree without dot entries or nested dist, so a bare match
  // under the lockfile hasher never short-circuits the installed baseline.)
  const unchangedUnderOwnFormula = entry.sourceTreeShaAlgo === 2
    ? hashSourceTree(sourcePath) === entry.sourceTreeSha
    : liveSha === entry.sourceTreeSha || legacySourceTreeSha(sourcePath) === entry.sourceTreeSha
  if (!unchangedUnderOwnFormula) {
    return { liveSha, changed: true, needsAlgoMigration: false }
  }
  // Unchanged as far as the old formula could see: the installed tree is the
  // only honest baseline for what it could not. A dependency lockfile the
  // INSTALLER generated (`bun install` writes one when the source ships
  // none) is the build's, not the source's — omitted from the baseline
  // (review r10 #2); a lockfile the source ships is compared like any file.
  const installerGenerated = new Set(BUN_LOCKFILES.filter((name) => !existsSync(join(sourcePath, name)) && existsSync(join(installedDir, name))))
  const installedSha = existsSync(installedDir) ? computeSourceTreeSha(installedDir, { omitRootEntries: installerGenerated }) : null
  const changed = installedSha === null || liveSha !== installedSha
  return { liveSha, changed, needsAlgoMigration: !changed }
}

/** The lockfiles `bun install --ignore-scripts` may create inside an installed plugin. */
const BUN_LOCKFILES = ['bun.lock', 'bun.lockb'] as const
